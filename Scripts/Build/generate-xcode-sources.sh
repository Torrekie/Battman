#!/bin/sh
# Shared source-generation phase for all four Battman application targets.

set -eu

: "${PROJECT_DIR:?PROJECT_DIR is required}"
: "${DERIVED_FILE_DIR:?DERIVED_FILE_DIR is required}"
: "${CURRENT_PROJECT_VERSION:?CURRENT_PROJECT_VERSION is required}"
: "${CONFIGURATION:?CONFIGURATION is required}"
: "${PRODUCT_BUNDLE_IDENTIFIER:?PRODUCT_BUNDLE_IDENTIFIER is required}"
: "${SCRIPT_INPUT_FILE_0:?SCRIPT_INPUT_FILE_0 is required}"
: "${SCRIPT_OUTPUT_FILE_0:?SCRIPT_OUTPUT_FILE_0 is required}"

PATH=/opt/homebrew/bin:$PATH
export PATH

printf '%s\n' "const unsigned char lh_arr[] = {" > "${SCRIPT_OUTPUT_FILE_0}"
openssl sha256 -c "${SCRIPT_INPUT_FILE_0}" |
    gsed "s/^.*= /0x/g;s/:/,0x/g" >> "${SCRIPT_OUTPUT_FILE_0}"
printf '%s\n' "};" >> "${SCRIPT_OUTPUT_FILE_0}"

if [ -e "${PROJECT_DIR}/Battman/gen_locale_hashes.py" ]; then
    rm -f "${DERIVED_FILE_DIR}/mo_verification.h"
    locale_directory="${PROJECT_DIR}/${PROJECT_NAME}/locales"
    if [ ! -d "${locale_directory}" ]; then
        printf '%s\n' "error: locale directory is missing: ${locale_directory}" >&2
        exit 2
    fi
    locale_list="${DERIVED_FILE_DIR}/battman-locale-inputs.txt"
    find "${locale_directory}" -type f -name battman.mo -print | LC_ALL=C sort > "${locale_list}"
    if [ ! -s "${locale_list}" ]; then
        printf '%s\n' "error: no compiled Battman locales were found" >&2
        exit 2
    fi
    # Paths generated by Xcode's locale phase contain no whitespace. Reject it
    # explicitly instead of relying on implicit shell word splitting.
    if grep '[[:space:]]' "${locale_list}" >/dev/null; then
        printf '%s\n' "error: locale path contains whitespace" >&2
        exit 2
    fi
    # shellcheck disable=SC2046
    python3 "${PROJECT_DIR}/Battman/gen_locale_hashes.py" \
        --out "${DERIVED_FILE_DIR}/mo_verification" $(cat "${locale_list}")
fi

PYTHONDONTWRITEBYTECODE=1 python3 \
    "${PROJECT_DIR}/Scripts/Build/generate-build-identity.py" \
    --repo "${PROJECT_DIR}" \
    --version "${CURRENT_PROJECT_VERSION}" \
    --configuration "${CONFIGURATION}" \
    --product-identifier "${PRODUCT_BUNDLE_IDENTIFIER}" \
    --output "${DERIVED_FILE_DIR}/BattmanBuildIdentity.json"
